    /** 按 tick 取插值后的位置与朝向偏移 */
    public static float[] at(int tick) {
        if (tick <= PATH[0][0]) {
            return PATH[0];
        }
        for (int i = 0; i < PATH.length - 1; i++) {
            float[] a = PATH[i];
            float[] b = PATH[i + 1];
            if (tick >= a[0] && tick <= b[0]) {
                float k = (tick - a[0]) / Math.max(1.0F, b[0] - a[0]);
                // 必须返回 5 个值（tick + x + y + z + yaw），
                // 调用方按 PATH 的列索引取值，少一列就越界
                return new float[] {
                        tick,
                        a[1] + (b[1] - a[1]) * k,
                        a[2] + (b[2] - a[2]) * k,
                        a[3] + (b[3] - a[3]) * k,
                        a[4] + (b[4] - a[4]) * k,
                };
            }
        }
        return PATH[PATH.length - 1];
    }
